from datetime import datetime
from sqlalchemy import Column, Integer, String, Text, Boolean, DateTime, ForeignKey
from sqlalchemy.orm import relationship
from app.database import Base
from app.models.base import TimestampMixin


class EmailMessage(Base, TimestampMixin):
    """
    Records email message history, timestamps, status, provider metadata, and error details.
    Tokens and credentials are never stored in message records.
    """
    __tablename__ = "email_messages"

    id = Column(Integer, primary_key=True, index=True)
    contact_id = Column(Integer, ForeignKey("contacts.id", ondelete="SET NULL"), nullable=True, index=True)
    client_id = Column(Integer, ForeignKey("clients.id", ondelete="SET NULL"), nullable=True, index=True)
    project_id = Column(Integer, ForeignKey("projects.id", ondelete="SET NULL"), nullable=True, index=True)

    recipient_email = Column(String(255), nullable=False, index=True)
    recipient_name = Column(String(120), nullable=True)
    sender_email = Column(String(255), nullable=False)
    subject = Column(String(255), nullable=False)
    body_text = Column(Text, nullable=False)
    body_html = Column(Text, nullable=True)

    # Status: 'queued', 'sent', 'failed', 'received'
    status = Column(String(30), default="sent", nullable=False, index=True)
    # Direction: 'outbound' (sent by employee), 'inbound' (incoming reply from client/contact)
    direction = Column(String(20), default="outbound", nullable=False, index=True)
    # Provider: 'mock', 'smtp', 'resend', 'sendgrid'
    provider = Column(String(50), default="mock", nullable=False)
    # External provider unique message id (e.g. Resend ID, SMTP Message-ID, or mock UUID)
    provider_message_id = Column(String(255), nullable=True, index=True)
    # Client-supplied idempotency key to prevent accidental duplicate sends
    idempotency_key = Column(String(120), nullable=True, index=True)
    # Clean error explanation if delivery failed (never credentials or access tokens)
    error_details = Column(Text, nullable=True)
    # Whether this email body was generated by AI follow-up assistant
    ai_drafted = Column(Boolean, default=False, nullable=False)
    sent_at = Column(DateTime, default=datetime.utcnow, nullable=True)

    # Relationships
    contact = relationship("Contact", back_populates="emails")
    client = relationship("Client", back_populates="emails")
    project = relationship("Project", back_populates="emails")

    def __repr__(self) -> str:
        return (
            f"<EmailMessage id={self.id} to='{self.recipient_email}' "
            f"direction='{self.direction}' status='{self.status}' provider='{self.provider}'>"
        )
